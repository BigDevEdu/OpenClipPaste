import AppKit

@MainActor
final class ClipboardMonitor {
    private let store: HistoryStore
    private var lastCount = -1
    private var timer: Timer?

    init(store: HistoryStore) { self.store = store }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// Função pura: o que fazer com um pasteboard que tem esses tipos (nil = ignorar).
    static func classify(types: [NSPasteboard.PasteboardType]) -> ClipKind? {
        let raw = Set(types.map(\.rawValue))
        let ignored = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType"]
        if !raw.isDisjoint(with: ignored) { return nil }
        if types.contains(.fileURL) { return nil }
        if types.contains(.png) || types.contains(.tiff) { return .image }
        if types.contains(.string) { return .text }
        return nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard let kind = Self.classify(types: pb.types ?? []) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        switch kind {
        case .image:
            let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff)
            guard let raw, let rep = NSBitmapImageRep(data: raw),
                  let png = rep.representation(using: .png, properties: [:]) else { return }
            store.add(.image(png: png, width: rep.pixelsWide, height: rep.pixelsHigh, source: source), pngData: png)
        case .text:
            guard let s = pb.string(forType: .string),
                  !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            store.add(.text(s, source: source))
        }
    }
}
